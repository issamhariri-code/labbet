PROFILE_HASH = '01234567' * 8
FIXED_CONTRACT_HASH = 'bf46034095363bf7a99f7bebd08d272426c085d32661879b95280cee39692ab4'
FIXED_MANIFEST_HASH = '7257327d693b1579c3f391652d74b9a18b5ca55b84f4af07138794c83a94d4fa'
FIXED_REQUEST_HASH = 'ae87ef862a23d36259f62f3e71d5046e1ecfc0477d0633ed57ba85e2973ea828'
FIXED_MANIFEST = (
    '{"availability":{"contract_fingerprint":"bf46034095363bf7a99f7bebd08d272426c085d32661879b95280cee39692ab4",'
    '"entries":[{"not_before":"2026-09-30T20:30:00.000000+00:00","session_date":"2026-09-30"}],'
    '"rule_version":"manual-v1","source_id":"source-a","version":1},"contract":{'
    '"accepted_timezones":[],"calendar_valid_from":"2026-09-30","calendar_valid_until":"2026-09-30",'
    '"calendar_version":"fixture-v1","currency":"USD","exchange":"TESTX","instrument_id":"TESTX:TEST",'
    '"max_age_seconds":3600,"max_rows":1,"minimum_sessions":1,"price_basis":"raw",'
    '"schema_version":"alphavantage-daily-v1","sessions":[["2026-09-30","2026-09-30T20:00:00+00:00"]],'
    '"symbol":"TEST","timezone":"UTC"},"version":1}'
)
FIXED_REQUEST = (
    '{"manifest_hash":"7257327d693b1579c3f391652d74b9a18b5ca55b84f4af07138794c83a94d4fa",'
    '"profile_config_hash":"0123456701234567012345670123456701234567012345670123456701234567",'
    '"request":{"contract_fingerprint":"bf46034095363bf7a99f7bebd08d272426c085d32661879b95280cee39692ab4",'
    '"reference_time":"2026-09-30T21:00:00.000000+00:00","sessions":["2026-09-30"]},"version":1}'
)


class RequestProvenanceTests(unittest.TestCase):
    def setUp(self):
        ZoneInfo('UTC')
        self.c = contract()
        self.p = self.make()

    def make(self, *, c=None, instant=NOW, source='source-a', rule='manual-v1',
             changes=None, profile_hash=PROFILE_HASH):
        c = self.c if c is None else c
        changes = {} if changes is None else changes
        a = SourceAvailability(source, rule, c.fingerprint,
            tuple(SessionAvailability(day, changes.get(day, close)) for day, close in c.sessions))
        return RequestProvenance(c, a, plan_daily_request(c, instant), profile_hash)

    def reject(self, operation, *args, code=None, **kwargs):
        with self.assertRaises(ApiFailure) as caught:
            operation(*args, **kwargs)
        if code is not None:
            self.assertEqual(caught.exception.code, code)
        self.assertNotIn('SYNTHETIC-PRIVATE', str(caught.exception))
        return caught.exception

    def bind(self, provenance=None, **changes):
        p = self.p if provenance is None else provenance
        c = p.contract
        args = dict(source_id=p.availability.source_id, instrument_id=c.instrument_id,
            symbol=c.symbol, observed_at=dict(c.sessions)[p.request.sessions[-1]],
            received_at=p.request.reference_time, config_version=p.config_version,
            metadata={'currency': c.currency, 'price_basis': c.price_basis,
                      'schema_version': c.schema_version, 'market_timezone': c.timezone,
                      'market': c.exchange}, session_dates=p.request.sessions)
        args.update(changes)
        return validate_provenance_binding(p, **args)

    def test_fixed_independent_documents_and_sha256_vectors(self):
        close = datetime(2026, 9, 30, 20, tzinfo=timezone.utc)
        c = contract(calendar_version='fixture-v1', calendar_valid_from=date(2026, 9, 30),
            calendar_valid_until=date(2026, 9, 30), sessions=((date(2026, 9, 30), close),),
            max_age_seconds=3600, max_rows=1)
        p = self.make(c=c, changes={date(2026, 9, 30): close + timedelta(minutes=30)})
        self.assertEqual(c.fingerprint, FIXED_CONTRACT_HASH)
        self.assertEqual(p.manifest_document, FIXED_MANIFEST)
        self.assertEqual(p.request_document, FIXED_REQUEST)
        self.assertEqual(p.manifest_hash, FIXED_MANIFEST_HASH)
        self.assertEqual(p.fingerprint, FIXED_REQUEST_HASH)
        self.assertEqual(hashlib.sha256(FIXED_MANIFEST.encode()).hexdigest(), FIXED_MANIFEST_HASH)
        self.assertEqual(hashlib.sha256(FIXED_REQUEST.encode()).hexdigest(), FIXED_REQUEST_HASH)
        self.assertEqual(provenance_from_documents(FIXED_MANIFEST, FIXED_REQUEST), p)

    def test_json_and_document_roundtrips_reproduce_all_bindings(self):
        for p in (self.p, self.make(profile_hash='f' * 64),
                  self.make(c=contract(minimum_sessions=2))):
            for decoded in (provenance_from_json(p.to_json()),
                    provenance_from_documents(p.manifest_document, p.request_document)):
                with self.subTest(method=decoded.fingerprint):
                    self.assertEqual(decoded, p)
                    self.assertEqual(decoded.config_version, p.config_version)
                    self.assertEqual(decoded.contract.fingerprint, p.contract.fingerprint)
                    self.assertIs(self.bind(decoded), decoded)

    def test_frozen_fields_slots_and_nested_values_resist_normal_assignment(self):
        self.assertFalse(hasattr(self.p, '__dict__'))
        for field in ('contract', 'availability', 'request', 'profile_config_hash'):
            with self.subTest(field=field), self.assertRaises(FrozenInstanceError):
                setattr(self.p, field, None)
        with self.assertRaises(FrozenInstanceError):
            self.p.contract.symbol = 'OTHER'
        with self.assertRaises(FrozenInstanceError):
            self.p.request.reference_time = NOW + timedelta(seconds=1)
        with self.assertRaises(TypeError):
            self.p.availability.entries[0] = self.p.availability.entries[1]

    def test_detached_json_can_be_mutated_without_changing_archived_object(self):
        original = (self.p.manifest_document, self.p.request_document, self.p.fingerprint)
        value = self.p.to_json()
        value['manifest']['contract']['sessions'][0][0] = '1900-01-01'
        value['manifest']['availability']['entries'][0]['not_before'] = 'bad'
        value['request']['request']['sessions'].clear()
        self.assertEqual((self.p.manifest_document, self.p.request_document, self.p.fingerprint), original)
        self.assertIsNot(self.p.contract, self.c)
        # Legacy DailyContract has a __dict__ despite frozen fields. The capture
        # must not alias this live object's dictionary or silently change later.
        self.c.__dict__.update(symbol='OTHER', calendar_version='changed-live-v2')
        self.assertEqual(self.p.contract.symbol, 'TEST')
        self.assertEqual((self.p.manifest_document, self.p.request_document, self.p.fingerprint), original)

    def test_exact_object_types_reject_subclasses_and_hostile_values(self):
        class ContractSubclass(DailyContract):
            pass
        class AvailabilitySubclass(SourceAvailability):
            pass
        class RequestSubclass(DailyRequest):
            pass
        variants = {
            'contract': ContractSubclass(**self.c.__dict__),
            'availability': AvailabilitySubclass(self.p.availability.source_id,
                self.p.availability.rule_version, self.c.fingerprint, self.p.availability.entries),
            'request': RequestSubclass(self.p.request.reference_time,
                self.p.request.contract_fingerprint, self.p.request.sessions),
        }
        for field, subclass in variants.items():
            for value in (subclass, None, {}, HostileValue()):
                with self.subTest(field=field, kind=type(value).__name__):
                    self.reject(replace, self.p, **{field: value}, code='invalid_provenance')

    def test_profile_hash_requires_exact_lowercase_sha256(self):
        class Text(str):
            pass
        for value in (None, True, b'a' * 64, 'A' * 64, 'a' * 63, 'a' * 65,
                      'g' * 64, Text('a' * 64), HostileValue()):
            with self.subTest(kind=type(value).__name__):
                self.reject(replace, self.p, profile_config_hash=value, code='invalid_provenance')

    def test_replace_revalidates_schedule_coverage_and_contract_binding(self):
        for a in (replace(self.p.availability, entries=self.p.availability.entries[:-1]),
                  replace(self.p.availability, contract_fingerprint='f' * 64)):
            self.reject(replace, self.p, availability=a)
        self.reject(replace, self.p, contract=replace(self.c, calendar_version='changed-v2'))

    def test_request_must_match_contract_fingerprint_and_exact_latest_targets(self):
        request = self.p.request
        for changed in (replace(request, contract_fingerprint='f' * 64),
                        replace(request, sessions=(date(2026, 9, 29),)),
                        replace(request, sessions=(date(2026, 9, 29), date(2026, 9, 30)))):
            self.reject(replace, self.p, request=changed, code='invalid_provenance')

    def test_not_yet_available_requested_session_cannot_be_archived(self):
        self.reject(self.make, changes={date(2026, 9, 30): NOW + timedelta(microseconds=1)},
                    code='data_not_available')
        p = self.make(changes={date(2026, 9, 30): NOW})
        self.assertIs(self.bind(p), p)

    def test_profile_hash_changes_request_identity_but_reuses_manifest(self):
        changed = replace(self.p, profile_config_hash='f' * 64)
        self.assertEqual(changed.manifest_document, self.p.manifest_document)
        self.assertEqual(changed.manifest_hash, self.p.manifest_hash)
        self.assertNotEqual(changed.request_document, self.p.request_document)
        self.assertNotEqual(changed.fingerprint, self.p.fingerprint)
        self.assertNotEqual(changed.config_version, self.p.config_version)

    def test_reference_microsecond_changes_request_not_manifest_or_config(self):
        changed = self.make(instant=NOW + timedelta(microseconds=1))
        self.assertEqual(changed.manifest_document, self.p.manifest_document)
        self.assertEqual(changed.config_version, self.p.config_version)
        self.assertNotEqual(changed.fingerprint, self.p.fingerprint)

    def test_source_rule_schedule_and_contract_changes_affect_manifest_identity(self):
        variants = (self.make(source='source-b'), self.make(rule='manual-v2'),
            self.make(changes={date(2026, 9, 29): NOW}),
            self.make(c=replace(self.c, calendar_version='calendar-v2')))
        for changed in variants:
            with self.subTest(hash=changed.manifest_hash):
                self.assertNotEqual(changed.manifest_hash, self.p.manifest_hash)
                self.assertNotEqual(changed.config_version, self.p.config_version)
                self.assertNotEqual(changed.fingerprint, self.p.fingerprint)

    def test_archive_preserves_old_contract_offset_representation_fingerprint(self):
        offset = timezone(timedelta(hours=2))
        c = replace(self.c, sessions=tuple((day, close.astimezone(offset)) for day, close in self.c.sessions))
        self.assertNotEqual(c.fingerprint, self.c.fingerprint)
        p = self.make(c=c)
        decoded = provenance_from_documents(p.manifest_document, p.request_document)
        self.assertEqual(decoded.contract.fingerprint, c.fingerprint)
        self.assertEqual(decoded.manifest_document, p.manifest_document)
        self.assertEqual(decoded.contract.sessions[0][1].utcoffset(), timedelta(hours=2))

    def test_archive_preserves_int_versus_float_fingerprint_without_coercion(self):
        integer, floating = self.p, self.make(c=replace(self.c, max_age_seconds=604800.0))
        self.assertNotEqual(integer.contract.fingerprint, floating.contract.fingerprint)
        for p in (integer, floating):
            decoded = provenance_from_documents(p.manifest_document, p.request_document)
            self.assertIs(type(decoded.contract.max_age_seconds), type(p.contract.max_age_seconds))
            self.assertEqual(decoded.contract.fingerprint, p.contract.fingerprint)

    def test_dst_fold_closes_remain_distinct_and_preserve_legacy_fingerprint(self):
        fingerprints = []
        for fold in (0, 1):
            close = datetime(2026, 11, 1, 1, 30, tzinfo=ZoneInfo('America/New_York'), fold=fold)
            day = date(2026, 11, 1)
            c = contract(timezone='America/New_York', calendar_valid_from=day,
                calendar_valid_until=day, sessions=((day, close),))
            p = self.make(c=c, instant=close.astimezone(timezone.utc) + timedelta(hours=1))
            decoded = provenance_from_documents(p.manifest_document, p.request_document)
            self.assertEqual(decoded.contract.fingerprint, c.fingerprint)
            self.assertEqual(decoded.manifest_document, p.manifest_document)
            fingerprints.append(decoded.manifest_hash)
        self.assertNotEqual(*fingerprints)

    def test_nonexistent_local_calendar_close_is_rejected(self):
        day = date(2026, 3, 8)
        close = datetime(2026, 3, 8, 2, 30, tzinfo=ZoneInfo('America/New_York'))
        c = contract(timezone='America/New_York', calendar_valid_from=day,
            calendar_valid_until=day, sessions=((day, close),))
        a = SourceAvailability('source-a', 'manual-v1', c.fingerprint,
                              (SessionAvailability(day, close.astimezone(timezone.utc)),))
        request = plan_daily_request(c, datetime(2026, 3, 8, 9, tzinfo=timezone.utc))
        self.reject(RequestProvenance, c, a, request, PROFILE_HASH, code='invalid_availability')

    def test_historical_decode_does_not_consult_current_adapter_registry(self):
        documents = self.p.manifest_document, self.p.request_document
        with (patch.object(api_adapters, '_DAILY_ADAPTERS', MappingProxyType({})),
              patch.object(api_adapters, 'daily_adapter_spec', side_effect=AssertionError('registry forbidden'))):
            decoded = provenance_from_documents(*documents)
        self.assertEqual(decoded.fingerprint, self.p.fingerprint)
        self.assertIs(self.bind(decoded), decoded)

    def test_construction_encoding_decoding_and_binding_are_pure_without_clock_or_io(self):
        documents = self.p.manifest_document, self.p.request_document
        value = self.p.to_json()
        with no_availability_side_effects():
            candidate = RequestProvenance(self.c, self.p.availability, self.p.request, PROFILE_HASH)
            decoded = provenance_from_documents(*documents)
            other = provenance_from_json(value)
            self.assertEqual(candidate.fingerprint, decoded.fingerprint)
            self.assertEqual(other.config_version, candidate.config_version)
            self.bind(candidate)
            self.assertEqual(candidate.to_json(), value)

    def test_json_schema_versions_shapes_unknown_and_missing_fields_are_rejected(self):
        paths = ((), ('manifest',), ('request',), ('request', 'request'), ('manifest', 'contract'))
        for path in paths:
            for action in ('extra', 'missing'):
                value = self.p.to_json()
                selected = value
                for field in path:
                    selected = selected[field]
                if action == 'extra':
                    selected['private'] = 'SYNTHETIC-PRIVATE'
                else:
                    selected.pop(next(iter(selected)))
                with self.subTest(path=path, action=action):
                    self.reject(provenance_from_json, value)
        for path in ((), ('manifest',), ('request',)):
            for version in (True, 0, 2, '1', None):
                value = self.p.to_json()
                selected = value
                for field in path:
                    selected = selected[field]
                selected['version'] = version
                with self.subTest(path=path, version=version):
                    self.reject(provenance_from_json, value, code='invalid_provenance')

    def test_json_rejects_nonexact_outer_dict_and_untrusted_object_values(self):
        class Dictionary(dict):
            pass
        for value in (None, True, [], 'SYNTHETIC-PRIVATE', Dictionary(self.p.to_json()), HostileValue()):
            with self.subTest(kind=type(value).__name__):
                self.reject(provenance_from_json, value, code='invalid_provenance')

    def test_contract_wire_rejects_bad_dates_naive_closes_and_mutable_shapes(self):
        variants = [('sessions', ()), ('sessions', []), ('sessions', [['20260930', '2026-09-30T20:00:00+00:00']]),
            ('sessions', [['2026-09-30', '2026-09-30T20:00:00']]),
            ('sessions', [['2026-09-30', 123]]), ('accepted_timezones', 'UTC'),
            ('calendar_valid_from', '20260929'), ('calendar_valid_until', None)]
        for field, item in variants:
            value = self.p.to_json()
            value['manifest']['contract'][field] = item
            with self.subTest(field=field, kind=type(item).__name__):
                self.reject(provenance_from_json, value)

    def test_request_wire_rejects_noncanonical_dates_naive_time_and_bad_sessions(self):
        for field, item in (('sessions', []), ('sessions', ()), ('sessions', ['20260930']),
            ('sessions', ['2026-09-30', '2026-09-30']), ('reference_time', NOW.replace(tzinfo=None).isoformat()),
            ('reference_time', None), ('contract_fingerprint', 'f' * 64)):
            value = self.p.to_json()
            value['request']['request'][field] = item
            with self.subTest(field=field, kind=type(item).__name__):
                self.reject(provenance_from_json, value)

    def test_manifest_integrity_rejects_hash_substitution_and_tampering(self):
        for item in ('f' * 64, None, [], 'SYNTHETIC-PRIVATE'):
            value = self.p.to_json()
            value['request']['manifest_hash'] = item
            self.reject(provenance_from_json, value, code='provenance_integrity')
        value = self.p.to_json()
        value['manifest']['availability']['rule_version'] = 'changed-v2'
        self.reject(provenance_from_json, value, code='provenance_integrity')

    def test_documents_require_canonical_bytes_not_only_equivalent_json(self):
        m, r = self.p.manifest_document, self.p.request_document
        for manifest, record in ((m + '\n', r), (m, r + ' '),
                (json.dumps(json.loads(m), indent=2), r),
                (m, r.replace('21:00:00.000000+00:00', '21:00:00+00:00'))):
            with self.subTest(manifest_changed=manifest != m):
                self.reject(provenance_from_documents, manifest, record, code='provenance_noncanonical')

    def test_documents_reject_duplicates_invalid_unicode_numbers_and_wrong_types(self):
        for text in ('{"version":1,"version":1}', '{"value":NaN}', '{"value":Infinity}',
                     '{"x":1e999}', '\ud800', '[invalid'):
            self.reject(provenance_from_documents, text, self.p.request_document)
            self.reject(provenance_from_documents, self.p.manifest_document, text)
        for value in (None, b'{}', {}, HostileValue()):
            self.reject(provenance_from_documents, value, self.p.request_document, code='invalid_provenance')

    def test_document_size_limits_fail_before_decoding(self):
        for manifest, record in (('x' * (4 * 1048576 + 1), self.p.request_document),
                                 (self.p.manifest_document, 'x' * 262145)):
            with patch.object(api_provenance, 'decode_json', side_effect=AssertionError('decode forbidden')):
                self.reject(provenance_from_documents, manifest, record, code='provenance_size')

    def test_constructor_exact_document_limits_and_one_byte_below(self):
        m, r = len(self.p.manifest_document.encode()), len(self.p.request_document.encode())
        with (patch.object(api_provenance, 'MAX_MANIFEST_BYTES', m),
              patch.object(api_provenance, 'MAX_REQUEST_BYTES', r)):
            self.assertEqual(replace(self.p), self.p)
        for field, limit in (('MAX_MANIFEST_BYTES', m - 1), ('MAX_REQUEST_BYTES', r - 1)):
            with patch.object(api_provenance, field, limit):
                self.reject(replace, self.p, code='provenance_size')

    def test_binding_checks_source_instrument_symbol_and_configuration(self):
        for field, value in (('source_id', 'source-b'), ('instrument_id', 'TESTX:OTHER'),
                             ('symbol', 'OTHER'), ('config_version', 'f' * 64)):
            with self.subTest(field=field):
                self.reject(self.bind, **{field: value}, code='provenance_binding')
        self.reject(validate_provenance_binding, None, source_id='source-a', instrument_id='TESTX:TEST',
            symbol='TEST', observed_at=NOW, received_at=NOW, config_version='f' * 64,
            metadata={}, session_dates=(), code='invalid_provenance')

    def test_binding_requires_exact_metadata_without_missing_extra_or_changed_meaning(self):
        metadata = {'currency': 'USD', 'price_basis': 'raw', 'schema_version': self.c.schema_version,
                    'market_timezone': 'UTC', 'market': 'TESTX'}
        for name in metadata:
            changed = dict(metadata, **{name: 'OTHER'})
            self.reject(self.bind, metadata=changed, code='provenance_binding')
            missing = dict(metadata)
            del missing[name]
            self.reject(self.bind, metadata=missing, code='provenance_binding')
        self.reject(self.bind, metadata=dict(metadata, adjustment_version='v1'), code='provenance_binding')

    def test_binding_checks_market_close_actual_receipt_and_age_not_only_request_time(self):
        self.reject(self.bind, observed_at=NOW, code='observation_mismatch')
        self.reject(self.bind, received_at=NOW - timedelta(microseconds=1), code='clock_rollback')
        self.reject(self.bind, received_at=NOW + timedelta(days=8), code='stale_data')
        for field in ('observed_at', 'received_at'):
            self.reject(self.bind, **{field: NOW.replace(tzinfo=None)}, code='invalid_availability')

    def test_binding_requires_exact_target_coverage_and_no_future_rows(self):
        for days in ([], (NOW,), (date(2026, 9, 30), date(2026, 9, 30))):
            self.reject(self.bind, session_dates=days, code='provenance_binding')
        self.reject(self.bind, session_dates=(), code='row_limit')
        self.reject(self.bind, session_dates=(date(2026, 9, 29),), code='incomplete_series')
        self.reject(self.bind, session_dates=(date(2026, 9, 30), date(2026, 10, 1)),
                    code='request_sessions_mismatch')
        self.assertIs(self.bind(session_dates=(date(2026, 9, 30), date(2026, 9, 29))), self.p)

    def test_binding_checks_every_extra_historical_rows_own_availability(self):
        p = self.make(changes={date(2026, 9, 29): NOW + timedelta(microseconds=1)})
        self.assertIs(self.bind(p), p)
        self.reject(self.bind, p, session_dates=(date(2026, 9, 29), date(2026, 9, 30)),
                    code='data_not_available')

    def test_accepted_and_rejected_json_inputs_are_unchanged(self):
        value = self.p.to_json()
        before = deepcopy(value)
        provenance_from_json(value)
        self.assertEqual(value, before)
        value['manifest']['availability']['entries'].pop()
        before = deepcopy(value)
        self.reject(provenance_from_json, value)
        self.assertEqual(value, before)


